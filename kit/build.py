def stamp():
    return "registry-generated"   # no wall-clock: keep output deterministic for --check

def main():
    refuse_if_worktree('kit/build.py')
    mode = sys.argv[1] if len(sys.argv) > 1 else ''
    reg = json.load(open(REG))
    comps = reg['components']

    drift = []
    for c in comps:
        cc = contract(c)
        stored = c.get('contract')
        if stored is None:                       # first stamp
            c['version'], c['contract'] = 1, cc
        elif stored != cc:
            drift.append((c['id'], stored, cc))

    if mode == '--restamp':
        for c in comps:
            cc = contract(c)
            if c.get('contract') != cc:
                c['version'] = c.get('version', 1) + 1
                c['contract'] = cc
        json.dump(reg, open(REG, 'w'), indent=2, ensure_ascii=False); open(REG,'a').write('\n')
        print("restamped."); return _print_ledger(comps)

    html_out, md_out = render_html(reg), render_md(reg)

    if mode == '--check':
        stale = drift or (open(IDX).read() != html_out) or (open(MD).read() != md_out)
        if drift:
            for i, s, cc in drift:
                print(f"DRIFT: {i} contract moved {s} -> {cc} without a version bump. Run: python3 kit/build.py --restamp")
        if open(IDX).read() != html_out or open(MD).read() != md_out:
            print("STALE: docs differ from the registry. Run: python3 kit/build.py")
        print("check FAILED" if stale else "check OK")
        sys.exit(1 if stale else 0)

    # normal build: stamp any first-time components, write docs
    if any(c.get('contract') == contract(c) and 'contract' in c for c in comps):
        json.dump(reg, open(REG, 'w'), indent=2, ensure_ascii=False); open(REG,'a').write('\n')
    open(IDX, 'w').write(html_out); open(MD, 'w').write(md_out)
    if drift:
        for i, s, cc in drift:
            print(f"WARNING: {i} contract moved {s} -> {cc}. Run --restamp to bump the version.")
    print(f"generated {os.path.relpath(MD, ROOT)} + {os.path.relpath(IDX, ROOT)}")
    _print_ledger(comps)

def _print_ledger(comps):
    print("\nid                 ver  contract")
    for c in comps:
        print(f"{c['id']:18} v{c.get('version')}  {c.get('contract')}")

if __name__ == '__main__':
    main()
