#!/usr/bin/env python3
"""BRG kit builder — generates the shortcode docs from kit/registry.json (the source
of truth), and stamps each component with a version + contract hash. Pattern borrowed
from fc-brands (temper/kit). Edit the registry, then run this — never edit the docs by hand.

  python3 kit/build.py            regenerate SHORTCODES.md + docs/shortcode-index.html
  python3 kit/build.py --restamp  bump version + re-hash any component whose contract moved
  python3 kit/build.py --check    exit 1 if a contract moved un-bumped, or the docs are stale
"""
import json, hashlib, sys, os, html, datetime

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _guard import refuse_if_worktree

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REG  = os.path.join(ROOT, 'kit', 'registry.json')
IDX  = os.path.join(ROOT, 'docs', 'shortcode-index.html')
MD   = os.path.join(ROOT, 'SHORTCODES.md')
E    = html.escape

def contract(c):
    """Hash of shortcode + type + every attr name=default. Prose is excluded on purpose."""
    canon = c['shortcode'] + '|' + c['type'] + '|' + '|'.join(
        f"{a['name']}={a.get('default','')}" for a in c.get('attrs', []))
    return hashlib.sha256(canon.encode('utf-8')).hexdigest()[:12]

GROUPS = [('pages', 'Whole-page shortcodes'), ('sections', 'Section shortcodes (stack these to build a page)'),
          ('chrome', 'Chrome (nav + footer)'), ('utility', 'Utility')]

# ---- SHORTCODES.md (markdown) -------------------------------------------------
def render_md(reg):
    L = ['# BRG — Shortcode Reference', '',
         '> GENERATED from `kit/registry.json` by `kit/build.py`. Edit the registry, then rerun. '
         'Do not edit this file by hand.', '',
         'Pages/sections are code fragments on Netlify pulled natively into WordPress; edit a fragment '
         '→ `git push` → live in ~60s. The nav is a WordPress menu (Appearance → Menus).', '',
         '## Shortcodes', '', '| Shortcode | Type | Attributes |', '|---|---|---|']
    for c in reg['components']:
        attrs = ', '.join(f"`{a['name']}`" for a in c.get('attrs', [])) or '—'
        L.append(f"| `[{c['shortcode']}]` | {c['type']} | {attrs} |")
    L += ['', '## Attributes by shortcode', '']
    for c in reg['components']:
        L.append(f"### `[{c['shortcode']}]` — {c['summary']}  ·  v{c['version']} `{c['contract']}`")
        if c.get('aliases'):
            L.append(f"Aliases: {c['aliases']}")
        L += ['', '| Attr | Default | Does |', '|---|---|---|']
        for a in c.get('attrs', []):
            opt = f" ({' / '.join(a['options'])})" if a.get('options') else ''
            L.append(f"| `{a['name']}`{opt} | `{a.get('default') or '—'}` | {a.get('doc','')} |")
        L.append('')
    L += ['## Global', '']
    for g in reg.get('globals', []):
        L.append(f"- `{g['name']}` (default `{g['default']}`) — {g['doc']}")
    L += ['', f"_registry v{reg['version']} · built {stamp()}_", '']
    return '\n'.join(L)

